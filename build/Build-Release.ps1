<#
.SYNOPSIS
    Builds the Win11Migrator release artifacts: MSI installer, portable .exe, portable .zip, SHA256SUMS.txt.
.DESCRIPTION
    Runs on Windows (locally or in GitHub Actions). Needs the .NET Framework C# compiler, which every
    Windows install has, and the WiX Toolset CLI for the MSI (`dotnet tool install --global wix`).

    Signing is optional. When WIN11MIGRATOR_SIGN_PFX (base64 of a .pfx) and WIN11MIGRATOR_SIGN_PASSWORD
    are set, every script, the launcher and the MSI are Authenticode-signed with an RFC 3161 timestamp.
    Without them the artifacts are unsigned and SHA256SUMS.txt is the integrity check.
.PARAMETER Version
    Defaults to Version in Config\AppSettings.json. Must be major.minor.patch (an MSI requirement).
.PARAMETER SkipMsi
    Build only the portable artifacts (for machines without WiX).
.EXAMPLE
    .\build\Build-Release.ps1
#>
#Requires -Version 5.1
[CmdletBinding()]
param(
    [string]$OutputPath,
    [string]$Version,
    [switch]$SkipMsi
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
if (-not $OutputPath) { $OutputPath = Join-Path $repo 'dist' }
$settings = Get-Content (Join-Path $repo 'Config\AppSettings.json') -Raw | ConvertFrom-Json
if (-not $Version) { $Version = [string]$settings.Version }
if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "Version '$Version' must look like 1.2.3" }
$publisher = if ($settings.Publisher) { [string]$settings.Publisher } else { 'Win11Migrator' }
$upgradeCode = 'A58CE451-D387-4419-89BA-92436D2C9BAB'   # never change: it is how upgrades find older installs

$names = @{
    Zip  = "Win11Migrator-$Version-portable.zip"
    Exe  = "Win11Migrator-$Version-portable.exe"
    Msi  = "Win11Migrator-$Version-x64.msi"
    Sums = 'SHA256SUMS.txt'
}

function Write-Step { param([string]$Text) Write-Host "==> $Text" -ForegroundColor Cyan }

function Get-SigningCertificate {
    if (-not $env:WIN11MIGRATOR_SIGN_PFX) { return $null }
    $bytes = [Convert]::FromBase64String($env:WIN11MIGRATOR_SIGN_PFX)
    $flags = [System.Security.Cryptography.X509Certificates.X509KeyStorageFlags]::Exportable
    return [System.Security.Cryptography.X509Certificates.X509Certificate2]::new($bytes, $env:WIN11MIGRATOR_SIGN_PASSWORD, $flags)
}

function Invoke-SignFile {
    # Authenticode with a timestamp, so signatures stay valid after the certificate expires
    param([string[]]$Paths, $Certificate)
    if (-not $Certificate) { return }
    $timestamp = if ($env:WIN11MIGRATOR_TIMESTAMP_URL) { $env:WIN11MIGRATOR_TIMESTAMP_URL } else { 'http://timestamp.digicert.com' }
    foreach ($path in $Paths) {
        $result = Set-AuthenticodeSignature -FilePath $path -Certificate $Certificate -HashAlgorithm SHA256 -TimestampServer $timestamp
        if ($result.Status -ne 'Valid') { throw "Signing failed for $($path): $($result.StatusMessage)" }
    }
}

function Get-CSharpCompiler {
    $csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
    if (-not (Test-Path $csc)) { throw "C# compiler not found at $csc" }
    return $csc
}

function New-WixSource {
    <#
    Writes a WiX v4+ package whose file list mirrors the staged folder. Component GUIDs are generated by
    WiX from each file's install path, so they stay stable across builds and upgrades work.
    #>
    param([string]$StageDir, [string]$Destination)

    $idOf = {
        param([string]$Prefix, [string]$Relative)
        $md5 = [System.Security.Cryptography.MD5]::Create()
        try { $hash = -join ($md5.ComputeHash([Text.Encoding]::UTF8.GetBytes($Relative.ToLowerInvariant())) | ForEach-Object { $_.ToString('x2') }) }
        finally { $md5.Dispose() }
        return "$Prefix$hash"
    }
    $escape = { param([string]$s) [System.Security.SecurityElement]::Escape($s) }

    $dirs = [System.Text.StringBuilder]::new()
    $components = [System.Text.StringBuilder]::new()
    $walk = $null
    $walk = {
        param([string]$Dir, [string]$DirId, [string]$Indent)
        foreach ($file in Get-ChildItem -LiteralPath $Dir -File | Sort-Object Name) {
            $rel = $file.FullName.Substring($StageDir.Length).TrimStart('\')
            [void]$components.AppendLine("      <Component Id=`"$(& $idOf 'c' $rel)`" Directory=`"$DirId`" Guid=`"*`" Bitness=`"always64`">")
            [void]$components.AppendLine("        <File Id=`"$(& $idOf 'f' $rel)`" Source=`"$(& $escape $file.FullName)`" KeyPath=`"yes`" />")
            [void]$components.AppendLine("      </Component>")
        }
        foreach ($sub in Get-ChildItem -LiteralPath $Dir -Directory | Sort-Object Name) {
            $rel = $sub.FullName.Substring($StageDir.Length).TrimStart('\')
            $subId = & $idOf 'd' $rel
            [void]$dirs.AppendLine("$Indent<Directory Id=`"$subId`" Name=`"$(& $escape $sub.Name)`">")
            & $walk $sub.FullName $subId "$Indent  "
            [void]$dirs.AppendLine("$Indent</Directory>")
        }
    }
    & $walk $StageDir 'INSTALLFOLDER' '          '

    $dirTree = $dirs.ToString()
    $componentList = $components.ToString()
    $p = & $escape $publisher
    @"
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Package Name="Win11Migrator" Manufacturer="$p" Version="$Version" UpgradeCode="$upgradeCode"
           Scope="perMachine" Compressed="yes" InstallerVersion="500">
    <SummaryInformation Description="Move apps, files and settings to a new Windows PC" />
    <MajorUpgrade DowngradeErrorMessage="A newer version of Win11Migrator is already installed." />
    <MediaTemplate EmbedCab="yes" />
    <Property Id="ARPURLINFOABOUT" Value="https://github.com/$(& $escape ([string]$settings.UpdateRepository))" />
    <Property Id="ARPNOMODIFY" Value="1" />

    <StandardDirectory Id="ProgramFiles64Folder">
      <Directory Id="PublisherFolder" Name="$p">
        <Directory Id="INSTALLFOLDER" Name="Win11Migrator">
$dirTree
        </Directory>
      </Directory>
    </StandardDirectory>

    <StandardDirectory Id="ProgramMenuFolder">
      <Component Id="StartMenuShortcut" Guid="*" Bitness="always64">
        <Shortcut Id="StartMenuWin11Migrator" Name="Win11Migrator" Description="Move apps, files and settings to a new PC"
                  Target="[INSTALLFOLDER]Win11Migrator.bat" WorkingDirectory="INSTALLFOLDER" Show="minimized" />
        <RegistryValue Root="HKLM" Key="Software\$p\Win11Migrator" Name="StartMenuShortcut" Type="integer" Value="1" KeyPath="yes" />
      </Component>
    </StandardDirectory>
    <StandardDirectory Id="DesktopFolder">
      <Component Id="DesktopShortcut" Guid="*" Bitness="always64">
        <Shortcut Id="DesktopWin11Migrator" Name="Win11Migrator" Description="Move apps, files and settings to a new PC"
                  Target="[INSTALLFOLDER]Win11Migrator.bat" WorkingDirectory="INSTALLFOLDER" Show="minimized" />
        <RegistryValue Root="HKLM" Key="Software\$p\Win11Migrator" Name="DesktopShortcut" Type="integer" Value="1" KeyPath="yes" />
      </Component>
    </StandardDirectory>

    <ComponentGroup Id="AppFiles">
$componentList
    </ComponentGroup>

    <Feature Id="Main" Title="Win11Migrator">
      <ComponentRef Id="StartMenuShortcut" />
      <ComponentRef Id="DesktopShortcut" />
      <ComponentGroupRef Id="AppFiles" />
    </Feature>
  </Package>
</Wix>
"@ | Set-Content -LiteralPath $Destination -Encoding UTF8
}

# --- Stage ---------------------------------------------------------------------------------------
Write-Step "Staging Win11Migrator $Version"
if (Test-Path $OutputPath) { Remove-Item $OutputPath -Recurse -Force }
$stage = Join-Path $OutputPath 'stage'
$work = Join-Path $OutputPath 'work'
New-Item -ItemType Directory -Path $stage, $work -Force | Out-Null
foreach ($item in 'Win11Migrator.ps1', 'Win11Migrator.bat', 'README.md', 'INSTALL.md', 'LICENSE', 'Config', 'Core', 'Modules', 'GUI', 'Reports', 'Tools') {
    Copy-Item -Path (Join-Path $repo $item) -Destination $stage -Recurse -Force
}
"Win11Migrator $Version`r`nPublisher: $publisher`r`nBuilt: $((Get-Date).ToUniversalTime().ToString('u'))" |
    Set-Content (Join-Path $stage 'VERSION.txt') -Encoding UTF8

$certificate = Get-SigningCertificate
if ($certificate) {
    Write-Step "Signing scripts as $($certificate.Subject)"
    Invoke-SignFile -Certificate $certificate -Paths @(Get-ChildItem $stage -Recurse -Include *.ps1, *.psd1 | ForEach-Object FullName)
} else {
    Write-Warning 'No signing certificate configured; building unsigned artifacts.'
}

# --- Portable zip --------------------------------------------------------------------------------
Write-Step 'Portable zip'
Add-Type -AssemblyName System.IO.Compression.FileSystem
$payload = Join-Path $work 'payload.zip'
[System.IO.Compression.ZipFile]::CreateFromDirectory($stage, $payload, 'Optimal', $false)
$zipRoot = Join-Path $work "Win11Migrator-$Version"
Copy-Item -Path $stage -Destination $zipRoot -Recurse
[System.IO.Compression.ZipFile]::CreateFromDirectory($zipRoot, (Join-Path $OutputPath $names.Zip), 'Optimal', $true)

# --- Portable exe --------------------------------------------------------------------------------
Write-Step 'Portable exe'
$assemblyInfo = Join-Path $work 'AssemblyInfo.cs'
@"
using System.Reflection;
[assembly: AssemblyTitle("Win11Migrator (portable)")]
[assembly: AssemblyDescription("Move apps, files and settings to a new Windows PC")]
[assembly: AssemblyCompany("$publisher")]
[assembly: AssemblyProduct("Win11Migrator")]
[assembly: AssemblyCopyright("MIT License. Copyright (c) 2026 AuthorityGate; Copyright (c) 2026 $publisher")]
[assembly: AssemblyVersion("$Version.0")]
[assembly: AssemblyFileVersion("$Version.0")]
"@ | Set-Content $assemblyInfo -Encoding UTF8
$exe = Join-Path $OutputPath $names.Exe
$cscArgs = @('/nologo', '/target:winexe', '/platform:x64', '/optimize+', "/out:$exe",
             "/resource:$payload,payload.zip",
             '/reference:System.IO.Compression.dll', '/reference:System.IO.Compression.FileSystem.dll', '/reference:System.Windows.Forms.dll',
             (Join-Path $PSScriptRoot 'PortableLauncher.cs'), $assemblyInfo)
& (Get-CSharpCompiler) @cscArgs
if ($LASTEXITCODE -ne 0) { throw "csc failed with exit code $LASTEXITCODE" }
Invoke-SignFile -Certificate $certificate -Paths $exe

# --- MSI -----------------------------------------------------------------------------------------
if (-not $SkipMsi) {
    Write-Step 'MSI installer'
    if (-not (Get-Command wix -ErrorAction SilentlyContinue)) { throw 'WiX is not installed. Run: dotnet tool install --global wix' }
    $wxs = Join-Path $work 'Win11Migrator.wxs'
    New-WixSource -StageDir $stage -Destination $wxs
    $msi = Join-Path $OutputPath $names.Msi
    & wix build $wxs -arch x64 -o $msi
    if ($LASTEXITCODE -ne 0) { throw "wix build failed with exit code $LASTEXITCODE" }
    Invoke-SignFile -Certificate $certificate -Paths $msi
}

# --- Checksums -----------------------------------------------------------------------------------
Write-Step 'Checksums'
$artifacts = Get-ChildItem $OutputPath -File | Where-Object { $_.Name -ne $names.Sums } | Sort-Object Name
$artifacts | ForEach-Object { "$((Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant())  $($_.Name)" } |
    Set-Content (Join-Path $OutputPath $names.Sums) -Encoding ASCII

Remove-Item $stage, $work -Recurse -Force
Write-Step "Done: $OutputPath"
Get-ChildItem $OutputPath -File | Format-Table Name, @{ n = 'MB'; e = { [math]::Round($_.Length / 1MB, 2) } } -AutoSize
